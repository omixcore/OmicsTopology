"""The reproduction kit's own statistics must stand on their own.

``reproduce/verify.py`` deliberately re-implements the Wilson interval, the
exact binomial test and Benjamini-Hochberg instead of importing them, so that
a bug in the package's statistics module cannot certify itself.  These tests
pin that second implementation to hand-checkable values, and run the verifier
itself end to end.
"""

import pathlib
import subprocess
import sys

_HERE = pathlib.Path(__file__).resolve().parent
_REPO = _HERE.parent
sys.path.insert(0, str(_REPO / "reproduce"))

import verify  # noqa: E402


def test_wilson_reproduces_the_published_interval():
    # 8/10 vs a fair coin: the audit's own Wilson interval, [0.49, 0.943]
    lo, hi = verify.wilson(8, 10)
    assert pytest_approx(lo, 0.4901, 5e-4)
    assert pytest_approx(hi, 0.9433, 5e-4)
    # degenerate cases stay in [0, 1]
    assert verify.wilson(0, 5)[0] == 0.0
    assert verify.wilson(5, 5)[1] <= 1.0
    assert verify.wilson(0, 0) == (0.0, 1.0)


def pytest_approx(value, want, tol):
    return abs(value - want) <= tol


def test_binomial_reproduces_the_published_p_value():
    # 8/10 vs 0.5: the audit's exact two-sided p = 0.1094
    assert abs(verify.binom_two_sided(8, 10) - 0.1094) < 5e-4
    # symmetry of the two-sided test about its tails
    assert abs(verify.binom_two_sided(0, 10) - verify.binom_two_sided(10, 10)) < 1e-12
    assert verify.binom_two_sided(0, 10) < 0.005
    # a fair split is never significant
    assert verify.binom_two_sided(5, 10) > 0.99
    # extreme case is tiny
    assert verify.binom_two_sided(0, 50) < 1e-13


def test_benjamini_hochberg_takes_the_largest_holding_rank():
    # m = 4, thresholds .0125/.025/.030/.0417:
    # 0.001 and 0.002 hold, 0.04 fails at rank 3, 0.5 fails -> 2 survive
    assert verify.benjamini_hochberg([0.001, 0.002, 0.04, 0.5]) == 2
    # nothing survives a null family
    assert verify.benjamini_hochberg([0.6, 0.7, 0.8]) == 0
    # everything survives an already-clean family
    assert verify.benjamini_hochberg([0.001, 0.002, 0.003]) == 3
    assert verify.benjamini_hochberg([]) == 0


def test_the_verifier_passes_end_to_end_on_this_repo():
    """The recomputation layers must pass right now, in this tree.

    Integrity is skipped (the manifest is regenerated by make_manifest.py and
    is allowed to lag during development); every recomputation layer runs.
    """
    r = subprocess.run(
        [sys.executable, str(_REPO / "reproduce" / "verify.py"),
         "--skip-integrity"],
        capture_output=True, text=True)
    assert r.returncode == 0, r.stdout[-1500:] + r.stderr[-500:]
    assert "FAIL" not in r.stdout
