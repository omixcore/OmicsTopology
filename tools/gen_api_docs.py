"""Generate ``docs/api.md`` from the package's public surface.

Why generate rather than hand-write
-----------------------------------
A hand-written reference drifts the moment a signature changes, and a
reference that lies is worse than none.  This script reads the modules, pulls
the ``__all__`` lists, the real signatures and the first paragraph of every
docstring, and emits one deterministic Markdown file.  ``--check`` re-generates
it in memory and fails if the committed file differs, so CI catches drift
instead of a reader catching it.

    python tools/gen_api_docs.py            # write docs/api.md
    python tools/gen_api_docs.py --check    # exit 1 if it is out of date

Only the standard library and the package itself are used.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
_SRC = os.path.join(_ROOT, "src")
if _SRC not in sys.path:
    sys.path.insert(0, _SRC)

# Ordered so the reference reads as a pipeline: build a space, then measure it.
MODULES = [
    ("omictopo.geometry", "Distance, standardisation and embeddings"),
    ("omictopo.filtration", "Vietoris-Rips complexes and thresholds"),
    ("omictopo.homology", "Persistent homology backends"),
    ("omictopo.diagram", "Persistence diagrams as objects"),
    ("omictopo.compare", "Distances between diagrams"),
    ("omictopo.stats", "Permutation tests, corrections and intervals"),
    ("omictopo.cycles", "Representative cycles, cyclic order, cycle counts"),
    ("omictopo.protocol", "The calibrated inference protocol: cloud -> status"),
    ("omictopo.pipeline", "End-to-end comparison of two state clouds"),
    ("omictopo.summary", "Human-readable reports"),
    ("omictopo.io", "Reading and writing tables"),
    ("omictopo.datasets", "Synthetic state spaces with known topology"),
    ("omictopo.plots", "Figures (requires the plot extra)"),
    ("omictopo.cli", "Command line entry point"),
]

HEADER = """# API reference

*Generated by `tools/gen_api_docs.py`; do not edit by hand. CI fails if this
file is out of date with the source.*

The package is small on purpose. Everything public is listed below, grouped by
the stage of the analysis it belongs to. Every function that could mislead
carries a note on its assumptions in its own docstring — read those before
quoting a number.

"""


def _short(text: str | None) -> str:
    """First paragraph of a docstring, flattened onto one line."""
    if not text:
        return "*(no description)*"
    para = text.strip().split("\n\n")[0]
    line = " ".join(part.strip() for part in para.strip().splitlines())
    return line.replace("|", "\\|")


def _signature(obj) -> str:
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return "(...)"
    text = str(sig)
    # drop `self`/`cls` noise and keep the line readable
    return text.replace("(self, ", "(").replace("(self)", "()")


def _document(name: str, obj, out: list, level: str = "###") -> None:
    if inspect.isclass(obj):
        out.append(f"{level} `{name}`")
        out.append("")
        out.append(_short(obj.__doc__))
        out.append("")
        try:
            members = inspect.getmembers(obj, predicate=inspect.isfunction)
        except Exception:
            members = []
        public = [(m, f) for m, f in members
                  if not m.startswith("_") and f.__qualname__.startswith(obj.__name__)]
        if public:
            out.append("| member | signature |")
            out.append("| --- | --- |")
            for mname, fn in sorted(public):
                out.append(f"| `{mname}` | `{mname}{_signature(fn)}` |")
            out.append("")
        return

    if inspect.isfunction(obj) or inspect.isbuiltin(obj):
        out.append(f"{level} `{name}{_signature(obj)}`")
    else:
        out.append(f"{level} `{name}`")
    out.append("")
    out.append(_short(getattr(obj, "__doc__", None)))
    out.append("")


def render() -> str:
    out = [HEADER.rstrip("\n"), ""]
    out.append("## Contents")
    out.append("")
    for module, blurb in MODULES:
        anchor = module.replace(".", "")
        out.append(f"- [{module}](#{anchor}) — {blurb}")
    out.append("")
    out.append("---")
    out.append("")

    unavailable = []
    for module, blurb in MODULES:
        out.append(f"## {module.replace('.', '')}")
        out.append("")
        out.append(f"*{blurb}*")
        out.append("")
        try:
            mod = importlib.import_module(module)
        except Exception as exc:                       # optional dependency
            unavailable.append((module, exc.__class__.__name__))
            out.append(f"*Not importable in this environment: `{exc.__class__.__name__}`.*")
            out.append("")
            continue

        names = list(getattr(mod, "__all__", []))
        if not names:
            names = sorted(n for n, v in vars(mod).items()
                           if not n.startswith("_")
                           and (inspect.isfunction(v) or inspect.isclass(v))
                           and getattr(v, "__module__", "") == module)
        if not names:
            out.append("*No public objects.*")
            out.append("")
            continue
        for name in sorted(names):
            obj = getattr(mod, name, None)
            if obj is None:
                continue
            _document(name, obj, out)
    if unavailable:
        out.append("---")
        out.append("")
        out.append("Modules skipped in this environment: "
                   + ", ".join(f"`{m}` ({why})" for m, why in unavailable) + ".")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="fail instead of writing when the file is out of date")
    ap.add_argument("--out", default=os.path.join(_ROOT, "docs", "api.md"))
    args = ap.parse_args(argv)

    text = render()
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as fh:
                current = fh.read()
        except FileNotFoundError:
            print(f"FAIL {args.out} is missing; run tools/gen_api_docs.py")
            return 1
        if current != text:
            print(f"FAIL {args.out} is out of date; run tools/gen_api_docs.py")
            return 1
        print(f"ok   {args.out} is current")
        return 0

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
